import streamlit as st
import pandas as pd
import numpy as np
import joblib
from pathlib import Path

# -----------------------------
# Page configuration
# -----------------------------
st.set_page_config(
    page_title="House Price Predictor",
    page_icon="🏠",
    layout="wide"
)

# -----------------------------
# Load files
# -----------------------------
MODEL_PATH = Path("model.joblib")
DATA_PATH = Path("train.csv")

st.title("🏠 House Price Prediction")
st.write(
    "Enter the house characteristics below to estimate its sale price "
    "using the trained machine learning model."
)

if not MODEL_PATH.exists():
    st.error(
        "model.joblib was not found. Put the saved model in the same folder "
        "as app.py."
    )
    st.stop()

if not DATA_PATH.exists():
    st.error(
        "train.csv was not found. Put train.csv in the same folder as app.py "
        "because it is used to identify the model input columns and categories."
    )
    st.stop()

try:
    model = joblib.load(MODEL_PATH)
    train_df = pd.read_csv(DATA_PATH)
except Exception as error:
    st.error(f"Could not load the model or dataset: {error}")
    st.stop()

# The model was trained without Id and SalePrice.
feature_df = train_df.drop(
    columns=["Id", "SalePrice"],
    errors="ignore"
)

# Use one real row as the initial input so the default values form a
# realistic combination of house features instead of independent medians.
default_row = feature_df.iloc[0].copy()

numeric_columns = feature_df.select_dtypes(
    include=["number"]
).columns.tolist()

# Identify integer-like features so the UI does not show meaningless decimals.
# Examples: years, counts, ratings, and binary indicators.
integer_keywords = (
    "year", "yr", "age", "cars", "car", "fullbath", "half_bath",
    "bedroom", "kitchen", "room", "fireplace", "garage", "pool",
    "quality", "condition", "overall", "month", "miscval", "count"
)

def is_integer_feature(column, series):
    name = column.lower().replace(" ", "_")
    numeric = pd.to_numeric(series, errors="coerce").dropna()
    if numeric.empty:
        return False
    keyword_match = any(keyword in name for keyword in integer_keywords)
    all_values_are_integers = np.all(np.isclose(numeric % 1, 0))
    return keyword_match or all_values_are_integers

integer_columns = [
    column for column in numeric_columns
    if is_integer_feature(column, feature_df[column])
]
float_columns = [column for column in numeric_columns if column not in integer_columns]

categorical_columns = feature_df.select_dtypes(
    include=["object", "category", "bool"]
).columns.tolist()

# -----------------------------
# Sidebar
# -----------------------------
with st.sidebar:
    st.header("Model Information")
    st.write("Model: Lasso / GridSearchCV Pipeline")
    st.write(f"Input features: {feature_df.shape[1]}")
    st.write(f"Numeric features: {len(numeric_columns)}")
    st.write(f"Integer features: {len(integer_columns)}")
    st.write(f"Decimal features: {len(float_columns)}")
    st.write(f"Categorical features: {len(categorical_columns)}")
    st.info(
        "The prediction is generated by the model saved in model.joblib."
    )

# -----------------------------
# Create user input
# -----------------------------
user_input = {}

with st.form("house_prediction_form"):
    st.subheader("House Features")
    st.caption("The initial values come from one real row in the training dataset to keep the default house profile realistic.")

    if categorical_columns:
        with st.expander("Categorical Features", expanded=True):
            categorical_cols = st.columns(3)

            for index, column in enumerate(categorical_columns):
                series = feature_df[column]
                options = series.dropna().astype(str).unique().tolist()
                options = sorted(options)

                if not options:
                    options = ["None"]

                with categorical_cols[index % 3]:
                    user_input[column] = st.selectbox(
                        label=column,
                        options=options,
                        index=(options.index(str(default_row[column]))
                               if pd.notna(default_row[column])
                               and str(default_row[column]) in options else 0),
                        key=f"cat_{column}"
                    )

    if numeric_columns:
        with st.expander("Numerical Features", expanded=False):
            numeric_cols = st.columns(3)

            for index, column in enumerate(numeric_columns):
                series = pd.to_numeric(
                    feature_df[column],
                    errors="coerce"
                ).dropna()

                is_integer = column in integer_columns

                if series.empty:
                    default_value = 0
                    min_value = 0
                    max_value = 1
                else:
                    if is_integer:
                        default_value = int(round(series.median()))
                        min_value = int(np.floor(series.min()))
                        max_value = int(np.ceil(series.max()))
                    else:
                        default_value = float(series.median())
                        min_value = float(series.min())
                        max_value = float(series.max())

                    # Prefer the value from the same real row used for
                    # categorical defaults, when it is valid and in range.
                    row_value = pd.to_numeric(
                        pd.Series([default_row[column]]),
                        errors="coerce"
                    ).iloc[0]

                    if pd.notna(row_value):
                        if is_integer:
                            default_value = int(round(row_value))
                        else:
                            default_value = float(row_value)

                # Keep the widget usable even when min == max.
                if min_value == max_value:
                    min_value -= 1
                    max_value += 1

                step = 1 if is_integer else 0.01
                number_format = "%d" if is_integer else "%.2f"
                bounded_default = min(max(default_value, min_value), max_value)

                with numeric_cols[index % 3]:
                    user_input[column] = st.number_input(
                        label=column,
                        min_value=min_value,
                        max_value=max_value,
                        value=bounded_default,
                        step=step,
                        format=number_format,
                        key=f"num_{column}"
                    )

    submitted = st.form_submit_button(
        "Predict House Price",
        type="primary",
        use_container_width=True
    )

# -----------------------------
# Prediction
# -----------------------------
if submitted:
    try:
        input_df = pd.DataFrame(
            [user_input],
            columns=feature_df.columns
        )

        # Match the original training dtypes as closely as possible.
        for column in numeric_columns:
            input_df[column] = pd.to_numeric(
                input_df[column],
                errors="coerce"
            )

        for column in categorical_columns:
            input_df[column] = input_df[column].astype(str)

        prediction = model.predict(input_df)
        predicted_price = float(np.asarray(prediction).ravel()[0])

        if predicted_price < 0:
            st.error(
                "The model generated a negative price for this input. "
                "Try a realistic house profile or inspect the input values below."
            )
        else:
            st.success("Prediction completed successfully!")

        st.metric(
            label="Predicted Sale Price",
            value=f"${predicted_price:,.2f}"
        )

        with st.expander("Show submitted input"):
            st.dataframe(input_df, use_container_width=True)

    except Exception as error:
        st.error(
            "Prediction failed. Check that the model was trained with the "
            "same feature names and preprocessing pipeline."
        )
        st.exception(error)
